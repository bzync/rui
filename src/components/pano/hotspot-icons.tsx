const ACTION_ICONS: Record<string, PanoIconComponent> = {
  book: PanoIcons.Calendar,
  call: PanoIcons.Phone,
  directions: PanoIcons.MapPin,
  message: PanoIcons.Message,
}

export function getHotspotIcon(h: PanoHotspot): PanoIconComponent {
  if (h.icon && PANO_HOTSPOT_ICONS[h.icon]) return PANO_HOTSPOT_ICONS[h.icon].icon
  if (h.type === "scene") return PanoIcons.ArrowUp
  if (h.type === "media") return h.media?.kind === "video" ? PanoIcons.Video : PanoIcons.Image
  if (h.type === "link") return PanoIcons.ExternalLink
  if (h.type === "action") return ACTION_ICONS[h.action ?? "book"] ?? PanoIcons.Calendar
  return PanoIcons.Info
}

export const hotspotIcon = getHotspotIcon
